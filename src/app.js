import express from 'express';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getProvider, listProviders } from './infrastructure/agents/providers.js';
import { RunManager } from './infrastructure/process/run-manager.js';
import { FileConfigRepository } from './infrastructure/persistence/file-config-repository.js';
import { FileTaskIdSequence } from './infrastructure/persistence/file-task-id-sequence.js';
import { MarkdownTaskRepository } from './infrastructure/persistence/markdown-task-repository.js';
import { FilesystemProjectRepository } from './infrastructure/projects/filesystem-project-repository.js';
import { WindowsCliDiagnostics } from './infrastructure/agents/windows-cli-diagnostics.js';
import { WindowsFolderPicker } from './infrastructure/platform/windows-folder-picker.js';
import { ProjectService } from './application/projects/project-service.js';
import { TaskService } from './application/tasks/task-service.js';
import { StartTaskRun } from './application/agents/start-task-run.js';
import { createLocalRequestGuard } from './presentation/http/middleware/local-request-guard.js';
import { createTaskRouter } from './presentation/http/routes/tasks.routes.js';
import { createConfigRouter } from './presentation/http/routes/config.routes.js';
import { createProjectsRouter } from './presentation/http/routes/projects.routes.js';
import { createAgentsRouter } from './presentation/http/routes/agents.routes.js';
import { createRunsRouter } from './presentation/http/routes/runs.routes.js';
const here = path.dirname(fileURLToPath(import.meta.url));
export function createApp({ port = Number(process.env.PORT || 3030), homeDirectory = os.homedir(), platform = process.platform, folderPicker, cliDiagnostics } = {}) {
  folderPicker ||= new WindowsFolderPicker({ platform });
  cliDiagnostics ||= new WindowsCliDiagnostics({ platform });
  const rootState = { projectsRoot: '' };
  const configDir = path.join(homeDirectory, '.devdesk');
  const projectRepository = new FilesystemProjectRepository({ getProjectsRoot: () => rootState.projectsRoot });
  const configRepository = new FileConfigRepository({ configDir });
  const projectService = new ProjectService({ rootState, configRepository, projectRepository });
  const taskRepository = new MarkdownTaskRepository({ projectRepository, taskIdSequence: new FileTaskIdSequence() });
  const taskService = new TaskService({ taskRepository, projectRepository });
  const runManager = new RunManager({ configDir, timeoutMs: Number(process.env.DEVDESK_RUN_TIMEOUT_MS || 30 * 60 * 1000) });
  const providerRegistry = { getProvider, listProviders };
  const startTaskRun = new StartTaskRun({ taskService, providerRegistry, runManager, platform });
  const app = express();
  app.use(createLocalRequestGuard({ port }));
  app.use(express.json({ limit: '256kb' }));
  app.use(express.static(path.join(here, 'public')));
  app.use(createConfigRouter({ projectService, folderPicker, homeDirectory }));
  app.use(createProjectsRouter({ projectService }));
  app.use(createTaskRouter({ taskService }));
  app.use(createAgentsRouter({ providerRegistry, cliDiagnostics }));
  app.use(createRunsRouter({ runManager, startTaskRun }));
  return { app, services: { projectService, taskService, runManager, providerRegistry }, async initialize() { await Promise.all([projectService.initialize(), runManager.init()]); } };
}